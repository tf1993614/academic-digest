#!/usr/bin/env bash
# Regenerate the three committed client copies from skills/academic-digest/.
#
# The only file allowed to differ between the copies is references/scheduling.md:
# it is the source's references/scheduling/<client>.md plus a generated marker.
# Usage: scripts/sync-skills.sh [TARGET_ROOT]   # TARGET_ROOT defaults to this repo
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
source_dir="$root/skills/academic-digest"
target_root="${1:-$root}"
mkdir -p "$target_root"
target_root="$(cd "$target_root" && pwd)"

test "$target_root" != "/" || {
  echo "[fail] sync-skills: refusing to write into /" >&2
  exit 1
}
test -f "$source_dir/SKILL.md" || {
  echo "[fail] sync-skills: missing $source_dir/SKILL.md" >&2
  exit 1
}

copy_source_tree() {
  local dest="$1"
  (
    cd "$source_dir"
    tar \
      --exclude='references/scheduling' \
      --exclude='./references/scheduling' \
      --exclude='__pycache__' \
      --exclude='*/__pycache__' \
      --exclude='*.pyc' \
      --exclude='*.egg-info' \
      --exclude='.pytest_cache' \
      -cf - .
  ) | (
    cd "$dest"
    tar -xf -
  )
}

# client:scan-root. A new client needs one line here, one scheduling/<client>.md,
# and one COPIES entry in tests/test_skill_copies.py.
copies=0
for spec in "dsh:.dsh/skills" "claude:.claude/skills" "codex:.agents/skills"; do
  client="${spec%%:*}"
  scan_root="${spec#*:}"
  rel="$scan_root/academic-digest"
  dest="$target_root/$rel"

  scheduling_src="$source_dir/references/scheduling/$client.md"
  test -f "$scheduling_src" || {
    echo "[fail] sync-skills: missing $scheduling_src" >&2
    exit 1
  }

  rm -rf -- "$dest"
  mkdir -p "$dest"
  copy_source_tree "$dest"
  mkdir -p "$dest/references"
  {
    printf '<!-- generated by scripts/sync-skills.sh -->\n\n'
    cat "$scheduling_src"
  } >"$dest/references/scheduling.md"
  copies=$((copies + 1))
done

printf '[ok] sync-skills: %s copies regenerated under %s\n' "$copies" "$target_root"
