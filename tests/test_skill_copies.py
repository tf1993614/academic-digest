"""The committed client copies must match the canonical skill byte for byte.

The comparison is the check itself: ``scripts/check-skills.sh`` runs this file,
and ``scripts/check.sh`` runs the whole suite. A hand edit under ``.dsh/``,
``.claude/`` or ``.agents/`` therefore fails before commit. Each copy is
compared against the tree the sync script generates for that client, so even its
``references/scheduling.md`` must match; those per-client files are the only ones
allowed to differ between copies.

The file also proves the point of shipping the code inside the skill: a freshly
generated copy runs the offline collect from an unrelated working directory,
and every entry script resolves its own package even when ``PYTHONPATH`` points
at a decoy.
"""

from __future__ import annotations

import json
import os
import re
import subprocess
import sys
from pathlib import Path

from conftest import FIXTURES, NOW, collect_options

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "skills" / "academic-digest"
SYNC = ROOT / "scripts" / "sync-skills.sh"
ENTRY_SCRIPTS = ("collect", "digest", "doctor", "fulltext", "push")
SCHEDULING = Path("references") / "scheduling.md"
MARKER = "<!-- generated by scripts/sync-skills.sh -->"

# client -> (committed copy, snippets its scheduled entry must contain)
COPIES = {
    "dsh": (
        Path(".dsh") / "skills" / "academic-digest",
        ("task_board_create", "0 8 * * *"),
    ),
    "claude": (
        Path(".claude") / "skills" / "academic-digest",
        ('claude -p "/academic-digest"', "run-daily.sh claude"),
    ),
    "codex": (
        Path(".agents") / "skills" / "academic-digest",
        ("codex exec", "run-daily.sh codex"),
    ),
}


def _ignored_runtime_path(relative: Path) -> bool:
    """Caches are gitignored byproducts of running a copy, not committed content.

    Keep this in step with the excludes in ``scripts/sync-skills.sh``: what the
    sync never generates must not become drift just because a copy was run.
    """

    return (
        "__pycache__" in relative.parts
        or ".pytest_cache" in relative.parts
        or any(part.endswith(".egg-info") for part in relative.parts)
        or relative.suffix == ".pyc"
    )


def _tree(root: Path) -> tuple[set[Path], dict[Path, bytes], list[Path]]:
    """Content under ``root``; symlinks fail and runtime caches are separate.

    Runtime paths are returned, not silently dropped, so the committed copy can
    prove they are gitignored rather than committed content.
    """

    dirs: set[Path] = set()
    files: dict[Path, bytes] = {}
    runtime: list[Path] = []
    for path in root.rglob("*"):
        relative = path.relative_to(root)
        assert not path.is_symlink(), f"{root}: symlink {relative} is not allowed in a copy"
        if _ignored_runtime_path(relative):
            runtime.append(relative)
        elif path.is_dir():
            dirs.add(relative)
        elif path.is_file():
            files[relative] = path.read_bytes()
    return dirs, files, runtime


def _assert_untracked_runtime(copy: Path, runtime: list[Path]) -> None:
    """A cache in a copy is tolerated only if git would never commit it."""

    if not runtime:
        return
    probe = subprocess.run(
        ["git", "-C", str(ROOT), "rev-parse", "--show-toplevel"],
        capture_output=True,
        text=True,
    )
    assert probe.returncode == 0, (
        f"{copy}: runtime files {runtime} exist without git metadata to prove them "
        "untracked; a checked-out copy must contain only committed files"
    )
    for relative in runtime:
        tracked = subprocess.run(
            ["git", "-C", str(ROOT), "ls-files", "--error-unmatch", "--",
             str((copy / relative).relative_to(ROOT))],
            capture_output=True,
            text=True,
        )
        assert tracked.returncode != 0, f"{copy}: {relative} is tracked; caches must not be committed"


def _sync_to(target: Path) -> None:
    result = subprocess.run(
        ["bash", str(SYNC), str(target)],
        capture_output=True,
        text=True,
        timeout=60,
    )
    assert result.returncode == 0, result.stderr
    assert "[ok] sync-skills" in result.stdout


def test_copies_match_the_generated_tree(tmp_path: Path) -> None:
    _sync_to(tmp_path)
    scheduling_texts: set[bytes] = set()

    for client, (relative, _) in COPIES.items():
        generated = tmp_path / relative
        committed = ROOT / relative
        assert generated.is_dir(), f"{client}: sync did not generate {relative}"
        assert committed.is_dir(), f"{client}: committed copy {relative} is missing"

        expected_dirs, expected_files, _ = _tree(generated)
        actual_dirs, actual_files, actual_runtime = _tree(committed)
        assert actual_dirs == expected_dirs, (
            f"{client}: directory drift; missing={sorted(expected_dirs - actual_dirs)}, "
            f"extra={sorted(actual_dirs - expected_dirs)}"
        )
        assert set(actual_files) == set(expected_files), (
            f"{client}: file set drift; missing={sorted(set(expected_files) - set(actual_files))}, "
            f"extra={sorted(set(actual_files) - set(expected_files))}"
        )
        for path, content in expected_files.items():
            assert actual_files[path] == content, f"{client}: {path} drifts from the source tree"
        wrapper = committed / "scripts" / "run-daily.sh"
        assert os.access(wrapper, os.X_OK), (
            f"{client}: {wrapper.name} must stay executable; the scheduler invokes it directly"
        )
        _assert_untracked_runtime(committed, actual_runtime)

        scheduling_texts.add(actual_files[SCHEDULING])

    assert len(scheduling_texts) == len(COPIES), (
        "the per-client references/scheduling.md files must differ; that is the only "
        "allowed difference between copies"
    )


def test_each_copy_names_its_client_start_command() -> None:
    for client, (relative, commands) in COPIES.items():
        scheduling = ROOT / relative / SCHEDULING
        assert scheduling.is_file(), f"{client}: missing {relative / SCHEDULING}"
        text = scheduling.read_text(encoding="utf-8")
        assert text.startswith(MARKER), f"{client}: scheduling.md lacks the generated marker"
        for command in commands:
            assert command in text, f"{client}: scheduling.md must name {command!r}"
        assert not (ROOT / relative / "references" / "scheduling").is_dir(), (
            f"{client}: the per-client scheduling variants must not be distributed"
        )


def test_source_has_one_scheduling_variant_per_client() -> None:
    variants = {path.stem for path in (SOURCE / "references" / "scheduling").glob("*.md")}
    assert variants == set(COPIES)
    assert not (SOURCE / "references" / SCHEDULING.name).exists(), (
        "references/scheduling.md is generated into the copies, not edited in the source"
    )


SCHEDULING_INVOCATIONS = {
    "claude": "/path/to/repo/.claude/skills/academic-digest/scripts/run-daily.sh claude",
    "codex": "/path/to/repo/.agents/skills/academic-digest/scripts/run-daily.sh codex",
}


def _fenced_blocks(text: str) -> list[str]:
    """Shell/config snippets only, so prose instructions are not mistaken for them."""

    blocks: list[str] = []
    current: list[str] | None = None
    for line in text.splitlines():
        stripped = line.lstrip()
        if stripped.startswith(("```", "~~~")):
            if current is None:
                current = []
            else:
                blocks.append("\n".join(current))
                current = None
            continue
        if current is not None:
            current.append(line)
    return blocks


def test_cli_schedules_share_the_wrapper_and_pin_the_runtime_constraints() -> None:
    """The three scheduler recipes per CLI client, minus the traps.

    Each client offers a systemd unit and timer, a launchd plist and a crontab
    line, and every one of them calls the one wrapper. The docs also carry the
    three runtime constraints that bite outside a login shell (timezone, no
    catch-up, CRON_TZ cronie-only, plus the client-specific switch). The DSH
    card bypasses the wrapper, and no scheduling doc offers a cloud scheduler.
    """

    texts = {
        client: (ROOT / relative / SCHEDULING).read_text(encoding="utf-8")
        for client, (relative, _) in COPIES.items()
    }

    for client, invoke in SCHEDULING_INVOCATIONS.items():
        text = texts[client]
        wrapper, _, argument = invoke.rpartition(" ")
        assert f"ExecStart={invoke}" in text, f"{client}: missing the systemd ExecStart"
        assert "OnCalendar=*-*-* 08:00:00 Asia/Shanghai" in text, (
            f"{client}: the timer must pin the IANA timezone"
        )
        assert "Persistent=false" in text, f"{client}: a missed systemd run must not be replayed"
        assert f"<string>{wrapper}</string>" in text, f"{client}: missing the launchd ProgramArguments"
        assert f"<string>{argument}</string>" in text, f"{client}: launchd must pass {argument}"
        assert "<key>StartCalendarInterval</key>" in text, (
            f"{client}: missing the launchd calendar trigger"
        )
        assert f"0 8 * * * {invoke}" in text, f"{client}: missing the crontab line"
        assert "CRON_TZ" in text and "cronie" in text, (
            f"{client}: crontab snippets must say CRON_TZ only works on cronie"
        )
        assert "不补跑" in text, f"{client}: docs must state that a missed run is not replayed"
        # The scheduler section must not redo what the wrapper owns; the
        # manual-run prelude elsewhere in the doc may still source secrets.
        scheduler = text.split("## 三种调度器", 1)[1].split("## 用户级安装", 1)[0]
        for block in _fenced_blocks(scheduler):
            assert not re.search(r"(?m)^\s*cd\b", block), (
                f"{client}: scheduler snippets must leave cd to the wrapper"
            )
            for duplicated in ("set -a", "secrets.env", "flock", ">>"):
                assert duplicated not in block, (
                    f"{client}: scheduler snippets must leave {duplicated!r} to the wrapper"
                )

    assert "不要加 `--bare`" in texts["claude"], "claude docs must warn against --bare"
    for block in _fenced_blocks(texts["claude"]):
        assert "--bare" not in block, "no claude snippet may pass --bare"
    assert "sandbox_workspace_write.network_access=true" in texts["codex"], (
        "codex docs must switch the sandbox network on"
    )
    assert "不补跑" in texts["dsh"], "the DSH card must state that a missed run is not replayed"
    assert "run-daily.sh dsh" not in texts["dsh"], "DSH has no wrapper client argument"

    for client, text in texts.items():
        for cloud in ("GitHub Actions", "云端", "scheduled task"):
            assert cloud not in text, f"{client}: cloud scheduling is out of scope for this release"


def test_committed_wrappers_are_executable() -> None:
    """The scheduler invokes the wrapper directly, so the committed mode matters.

    The pre-commit hook checks the index out into a bare temp directory, where
    there is no git metadata to ask: there the executable bit on the checked-out
    file is the check, and that bit comes from the index. In a normal checkout
    the index mode is asserted directly.
    """

    for client, (relative, _) in COPIES.items():
        wrapper = relative / "scripts" / "run-daily.sh"
        assert os.access(ROOT / wrapper, os.X_OK), (
            f"{client}: {wrapper} is not executable; schedulers invoke it directly"
        )
        probe = subprocess.run(
            ["git", "-C", str(ROOT), "rev-parse", "--show-toplevel"],
            capture_output=True,
            text=True,
        )
        if probe.returncode != 0:
            continue
        result = subprocess.run(
            ["git", "-C", str(ROOT), "ls-files", "-s", "--", str(wrapper)],
            capture_output=True,
            text=True,
        )
        assert result.returncode == 0 and result.stdout.strip(), (
            f"{client}: {wrapper} is not tracked by git"
        )
        mode = result.stdout.split()[0]
        assert mode == "100755", (
            f"{client}: {wrapper} is committed as {mode}; schedulers invoke it directly"
        )


def _run_collect_from(skill: Path, workdir: Path, *, env: dict[str, str] | None = None):
    """Run a skill's own collect entry point from an unrelated working directory."""

    workdir.mkdir(parents=True, exist_ok=True)
    out = workdir / "candidates.json"
    child_env = os.environ.copy()
    child_env.pop("PYTHONPATH", None)
    child_env["PYTHONDONTWRITEBYTECODE"] = "1"
    if env:
        child_env.update(env)
    options = collect_options(
        FIXTURES / "walking", out=out, state_db=workdir / "state.sqlite3", now=NOW
    )
    result = subprocess.run(
        [sys.executable, str(skill / "scripts" / "collect.py"), *map(str, options)],
        cwd=workdir,
        env=child_env,
        capture_output=True,
        text=True,
        timeout=60,
    )
    return result, out


def test_copies_run_the_offline_collect(tmp_path: Path) -> None:
    """The whole point of moving the code into the skill: ``cp -r`` and run.

    Both the freshly synced tree and every committed copy are exercised, so the
    ticket's ".claude copy, not the source" check is literal and the generated
    files are proven runnable, not just byte-identical.
    """

    synced_root = tmp_path / "synced"
    _sync_to(synced_root)
    copies = {
        f"synced-{client}": synced_root / relative
        for client, (relative, _) in COPIES.items()
    }
    copies.update({client: ROOT / relative for client, (relative, _) in COPIES.items()})

    for label, copy in copies.items():
        assert (copy / "scripts" / "collect.py").is_file(), label
        assert (copy / "academic_digest" / "cli.py").is_file(), label

        result, out = _run_collect_from(copy, tmp_path / "work" / label)

        assert result.returncode == 0, f"{label}: {result.stderr}"
        assert "[ok] pubmed: 2 records" in result.stdout, label
        pool = json.loads(out.read_text(encoding="utf-8"))
        assert pool["generated_at"] == NOW, label
        assert {paper["pmid"] for paper in pool["papers"]} == {"39000001", "39000002"}, label


def test_entry_scripts_bootstrap_their_own_skill_directory(tmp_path: Path) -> None:
    """A shadow ``academic_digest`` earlier on ``sys.path`` must never be imported.

    The bootstrap has to put its own skill directory ahead of ``PYTHONPATH`` and
    of any installed copy, so a copied skill still runs its own code.
    """

    shadow = tmp_path / "shadow"
    (shadow / "academic_digest").mkdir(parents=True)
    (shadow / "academic_digest" / "__init__.py").write_text(
        'raise RuntimeError("shadow academic_digest was imported")\n',
        encoding="utf-8",
    )
    workdir = tmp_path / "work"
    workdir.mkdir()

    for skill in (SOURCE, *(ROOT / relative for relative, _ in COPIES.values())):
        for name in ENTRY_SCRIPTS:
            script = skill / "scripts" / f"{name}.py"
            result = subprocess.run(
                [sys.executable, str(script), "--help"],
                cwd=workdir,
                env={
                    **os.environ,
                    "PYTHONPATH": str(shadow),
                    "PYTHONDONTWRITEBYTECODE": "1",
                },
                capture_output=True,
                text=True,
                timeout=60,
            )
            assert "shadow academic_digest" not in result.stderr, (
                f"{skill.name}/{script.name}: PYTHONPATH shadowed the skill's package"
            )
            assert result.returncode == 0, f"{skill.name}/{script.name}: {result.stderr}"
            assert "usage:" in result.stdout, f"{script}: no CLI help"

    result, out = _run_collect_from(
        SOURCE, workdir, env={"PYTHONPATH": str(shadow)}
    )
    assert result.returncode == 0, result.stderr
    assert json.loads(out.read_text(encoding="utf-8"))["candidate_count"] == 2
